#!/usr/bin/env python3
"""Append trajectory-checkpoint entries to llm-persona-moral-metrics/config/models.yaml.

run_mfq_sampling.py resolves models through that registry, so each checkpoint
needs an entry. The block is written between fenced markers and rewritten in
place on every run, so this is idempotent and reversible: delete the block (or
run --remove) and the registry is back to its previous state.

Only the intermediate checkpoints get entries. Step 0 and the final step reuse
the existing published keys, so nothing is duplicated for them.

Entries mirror the published final variant's entry exactly except for
model_path. In particular the renderer override is emitted only when the run
config sets one, because a renderer mismatch between the intermediate
checkpoints and the published endpoint would silently break the curve.

Usage:
    python checkpoint-trajectory/register_models.py --dry-run
    python checkpoint-trajectory/register_models.py
    python checkpoint-trajectory/register_models.py --remove
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from trajectory_config import CHECKPOINTS_JSON, MODELS_YAML, RUNS, RUNS_BY_NAME

BEGIN = "  # >>> BEGIN checkpoint-trajectory (generated by checkpoint-trajectory/register_models.py) >>>"
END = "  # <<< END checkpoint-trajectory <<<"

# Grey, dotted: these are intermediate artifacts and should never be mistaken for
# a headline variant in any plot that reads the registry's plot block.
PLOT_COLOR = "#888888"
PLOT_LINESTYLE = ":"


def entry_yaml(run, step: int, sampler_path: str) -> str:
    stem = run.stem(step)
    lines = [
        f"  - key: {stem}",
        f"    label: {run.family} ({run.dataset} step {step}/{run.total_steps})",
        f"    provider: tinker",
        f"    model_name: {run.tinker_model}",
        f"    stem: {stem}",
        f"    request_kwargs:",
        f"      max_tokens: 1",
        f'      model_path: "{sampler_path}"',
    ]
    if run.renderer:
        lines.append(f"      renderer: {run.renderer}")
    lines += [
        f"    capabilities:",
        f"      sampling: true",
        f"      logit: false",
        f"      self: true",
        f"    plot:",
        f'      color: "{PLOT_COLOR}"',
        f'      linestyle: "{PLOT_LINESTYLE}"',
    ]
    return "\n".join(lines)


def build_block(cache: dict) -> tuple[str, int]:
    chunks: list[str] = []
    count = 0
    for run in RUNS:
        steps = cache.get(run.name, {})
        if not steps:
            continue
        chunks.append(f"  # --- {run.name}: {len(steps)} intermediate checkpoints "
                      f"(step 0 = {run.base_key}, step {run.total_steps} = {run.final_key})")
        for step_key in sorted(steps, key=int):
            chunks.append(entry_yaml(run, int(step_key), steps[step_key]["sampler_path"]))
            count += 1
    return "\n\n".join(chunks), count


def strip_block(text: str) -> str:
    if BEGIN not in text:
        return text
    head, rest = text.split(BEGIN, 1)
    if END not in rest:
        raise SystemExit("models.yaml has a BEGIN marker with no END marker; fix by hand")
    _, tail = rest.split(END, 1)
    return head.rstrip("\n") + "\n" + tail.lstrip("\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--remove", action="store_true", help="strip the generated block")
    args = parser.parse_args()

    text = MODELS_YAML.read_text()

    if args.remove:
        new = strip_block(text)
        if args.dry_run:
            print(f"would remove the generated block ({len(text) - len(new)} chars)")
            return
        MODELS_YAML.write_text(new)
        print(f"removed generated block from {MODELS_YAML}")
        return

    if not CHECKPOINTS_JSON.exists():
        raise SystemExit(f"missing {CHECKPOINTS_JSON}; run convert_checkpoints.py first")
    cache = json.loads(CHECKPOINTS_JSON.read_text())

    block, count = build_block(cache)
    if not count:
        raise SystemExit("no converted checkpoints recorded; nothing to register")

    base = strip_block(text).rstrip("\n")
    new = f"{base}\n\n{BEGIN}\n{block}\n{END}\n"

    if args.dry_run:
        print(block)
        print(f"\n-- would register {count} checkpoint entries in {MODELS_YAML}")
        return

    MODELS_YAML.write_text(new)
    print(f"registered {count} checkpoint entries in {MODELS_YAML}")

    # Fail loudly here rather than 14 hours into a sampling run.
    sys.path.insert(0, str(MODELS_YAML.parent.parent))
    try:
        from model_registry import model_config
    except ImportError as exc:
        print(f"warning: could not import model_registry to validate ({exc})")
        return
    for run in RUNS:
        for step_key in sorted(cache.get(run.name, {}), key=int):
            key = run.stem(int(step_key))
            model_config(key, capability="sampling")
    print("all registered keys resolve via model_registry")


if __name__ == "__main__":
    main()
